def _stem(tok: str) -> str:
    """Сверх-простой стем: первые 5 символов для слов ≥ 6, 4 для слов из 5,
    иначе как есть (короткие слова — точное совпадение)."""
    if len(tok) >= 8:
        return tok[:6]
    if len(tok) >= 6:
        return tok[:5]
    if len(tok) == 5:
        return tok[:4]
    return tok


def _toks(text: str) -> set:
    import re
    out = set()
    for t in re.findall(r"[a-zа-яё0-9]{3,}", (text or "").lower()):
        if t in _STOP:
            continue
        out.add(_stem(t))
    return out


def search(query: str, top_k: int = 3, scores: bool = False):
    """Стём-реверанс по базе знаний (синхронный, офлайн).

    Возврат: список записей; при `scores=True` — список пар
    (запись, score).

    Взвешивание: совпадение с вопросами записи (3.0) важнее, чем с
    тегами (1.5), id (1.0) и текстом ответа (0.5) — так «что такое
    нейросеть» отдаётся записи про нейросети, а не записям, где
    нейросети лишь упомянуты в тегах.
    """
    q_tokens = _toks(query)
    scored = []
    for e in BASE:
        q_set, tag_set, id_set, ans_set = set(), set(), set(), set()
        for t in e["q"]:
            q_set |= _toks(t)
        for t in e["tags"]:
            tag_set |= _toks(t)
        id_set = _toks(e["id"])
        ans_set = _toks(e["a"])
        score = (len(q_tokens & q_set) * 3.0
                 + len(q_tokens & tag_set) * 1.5
                 + len(q_tokens & id_set) * 1.0
                 + len(q_tokens & ans_set) * 0.5)
        if score > 0:
            scored.append((score, e))
    scored.sort(key=lambda t: -t[0])
    if scores:
        return [(e, s) for s, e in scored[:top_k]]
    return [e for _, e in scored[:top_k]]


def category_counts() -> dict:
    out: dict[str, int] = {}
    for e in BASE:
        out[e["cat"]] = out.get(e["cat"], 0) + 1
    return out


